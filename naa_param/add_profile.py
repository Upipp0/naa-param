"""Create a cluster profile — the ``naa-param add-profile`` subcommand.

A profile is the only cluster-specific part of the pipeline: the scheduler, the
account and partition/queue, the resource requests, the Gaussian scratch
location, and the shell block that loads modules and activates the environment.
``setup`` renders the job scripts from it, so targeting a new cluster — including
one running PBS instead of Slurm — means writing one of these files rather than
editing any job template.

This module builds that file from command-line flags — module loads in the order
given, then any raw shell lines, then the environment activation — validates it
through :class:`~naa_param.cluster.ClusterProfile`, and writes it next to the shipped
profiles so ``setup --profile <name>`` finds it by name.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from .backends import SCHEDULERS
from .cluster import ClusterProfile, available_profiles, load_profile, profiles_dir

# Profile names become file names and are typed on the command line.
_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")

# Every profile field except `env_setup`, which is rendered as a literal block
# at the end, in the order the shipped profiles list them.
#
# A field missing from this tuple is silently dropped by `--from`: the copy
# succeeds, the profile loads, and it is simply missing a setting. Adding a
# field to `ClusterProfile` means adding it here too, and
# `test_cluster_profile.py::TestProfileRoundTrip` fails until you do.
_FIELD_ORDER = (
    "name",
    "scheduler",
    "account",
    "partition",
    "nodes",
    "ntasks_per_node",
    "cpus",
    "mem",
    "time",
    "rename_cpus",
    "rename_mem",
    "rename_time",
    "gather_cpus",
    "gather_mem",
    "gather_time",
    "select",
    "extra_directives",
    "scratch_base",
)


def build_env_setup(
    modules: list[str] | None,
    env_lines: list[str] | None,
    venv: str | None,
    module_purge: bool = True,
) -> str:
    """Assemble the profile's shell block: modules, raw lines, then activation."""
    lines: list[str] = []
    if modules:
        if module_purge:
            lines.append("module purge")
        lines += [f"module load {m}" for m in modules]
    lines += list(env_lines or [])
    if venv:
        path = Path(venv)
        activate = path if path.name == "activate" else path / "bin" / "activate"
        lines.append(f'source "{activate}"')
    else:
        lines.append("# Activate the environment where `naa-param` is installed (EDIT):")
        lines.append('#   source "$HOME/naa_param/.venv/bin/activate"')
    return "\n".join(lines)


def _yaml_scalar(value: object) -> str:
    """Render *value* as a YAML scalar (strings quoted, None as an empty value)."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _yaml_value(key: str, value: object) -> list[str]:
    """A profile key as YAML lines — scalars inline, lists as a block.

    ``extra_directives`` is the only list field, and ``_yaml_scalar`` would
    render it as the string ``"['-l place=scatter']"`` — which loads back as a
    string and pydantic rejects. A profile that cannot be re-read is worse than
    one that was never written.
    """
    if isinstance(value, list):
        if not value:
            return [f"{key}: []"]
        return [f"{key}:"] + [f"  - {_yaml_scalar(item)}" for item in value]
    return [f"{key}: {_yaml_scalar(value)}".rstrip()]


def render_profile(data: dict) -> str:
    """Render a profile mapping as YAML, with ``env_setup`` as a literal block."""
    name = data["name"]
    lines = [
        f"# {name} cluster profile — generated by `naa-param add-profile`.",
        f"# Used by: naa-param setup ... --profile {name}",
    ]
    for key in _FIELD_ORDER:
        lines += _yaml_value(key, data.get(key))
    lines.append("env_setup: |")
    lines += [f"  {ln}" if ln.strip() else "" for ln in str(data["env_setup"]).splitlines()]
    return "\n".join(lines) + "\n"


def _build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="naa-param add-profile",
        description=(
            "Create a cluster profile so `naa-param setup --profile <name>` can "
            "target a new cluster."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Example — a Leonardo (CINECA) profile:\n"
            "  naa-param add-profile leonardo \\\n"
            "      --account IscrC_XXXX \\\n"
            "      --partition boost_usr_prod \\\n"
            "      --modules profile/chem-phys g16 amber python \\\n"
            "      --env-line '. $g16root/g16/bsd/g16.profile' \\\n"
            "      --venv $HOME/naa_param/.venv\n"
            "\n"
            "Example — a PBS site, starting from the shipped `pbs` template:\n"
            "  naa-param add-profile mysite --from pbs \\\n"
            "      --account PROJ01 --partition workq \\\n"
            "      --directive '-l place=scatter' \\\n"
            "      --modules g16 amber python \\\n"
            "      --venv $HOME/naa_param/.venv\n"
        ),
    )
    p.add_argument("name", metavar="NAME", help="Profile name (used as the file name).")
    p.add_argument(
        "--from",
        dest="base",
        metavar="PROFILE",
        help=(
            "Start from an existing profile (name or .yaml path) and change only "
            "the flags given. Its env_setup is kept unless a --modules/--env-line/"
            "--venv flag is passed."
        ),
    )

    sched = p.add_argument_group("scheduler settings")
    sched.add_argument(
        "--scheduler",
        choices=tuple(SCHEDULERS),
        help="Which dialect the job scripts are rendered in (default: slurm).",
    )
    sched.add_argument(
        "--account", metavar="ACCT", help="Account to charge (Slurm --account, PBS -A)."
    )
    sched.add_argument(
        "--partition", metavar="PART", help="Partition or queue (Slurm --partition, PBS -q)."
    )
    sched.add_argument("--nodes", type=int, metavar="N", help="Nodes per job (default: 1).")
    sched.add_argument("--cpus", type=int, metavar="N", help="CPUs per task (default: 32).")
    sched.add_argument("--mem", metavar="SIZE", help='Memory per node (e.g. "360000MB").')
    sched.add_argument("--time", metavar="HH:MM:SS", help="Wall-clock limit (default: 24:00:00).")
    sched.add_argument(
        "--scratch-base",
        metavar="EXPR",
        help='Shell expression for the Gaussian scratch base (e.g. "$CINECA_SCRATCH").',
    )
    sched.add_argument(
        "--directive",
        action="append",
        dest="directives",
        metavar="DIRECTIVE",
        help=(
            "Extra scheduler directive, verbatim and with its leading dash "
            "(repeatable), in the dialect of --scheduler: '-l place=scatter' or "
            "'-m n' on PBS, --directive=--qos=normal on Slurm. Attach a Slurm "
            "directive with '=': a value beginning with '--' is read as another "
            "option otherwise. Replaces the list --from supplied."
        ),
    )

    pbs = p.add_argument_group("PBS-only settings (ignored by the Slurm backend)")
    pbs.add_argument(
        "--select",
        metavar="EXPR",
        help=(
            "The whole `-l` resource request, as a format string over {nodes}, "
            '{cpus} and {mem_mb}. Default: "select={nodes}:ncpus={cpus}:mem={mem_mb}mb" '
            '(PBS Pro). A Torque site wants "nodes={nodes}:ppn={cpus}".'
        ),
    )

    env = p.add_argument_group("environment (rendered into the job scripts, in this order)")
    env.add_argument(
        "--modules",
        nargs="+",
        metavar="MOD",
        help="Modules to load, in order — each becomes a `module load MOD` line.",
    )
    env.add_argument(
        "--env-line",
        action="append",
        dest="env_lines",
        metavar="LINE",
        help="Extra shell line after the module loads (repeatable), e.g. sourcing g16.profile.",
    )
    env.add_argument(
        "--venv",
        metavar="PATH",
        help="Virtualenv to activate (its root, or the activate script itself).",
    )
    env.add_argument(
        "--no-module-purge",
        action="store_true",
        help="Do not start the module block with `module purge`.",
    )

    out = p.add_argument_group("output")
    out.add_argument(
        "-o",
        "--output",
        metavar="FILE",
        help="Write here instead of the profiles directory (use with --profile PATH).",
    )
    out.add_argument("--force", action="store_true", help="Overwrite an existing profile.")
    out.add_argument(
        "--dry-run", action="store_true", help="Print the profile instead of writing it."
    )
    return p


def main() -> int:
    """Entry point for the ``naa-param add-profile`` subcommand."""
    parser = _build_parser()
    args = parser.parse_args()

    if not _NAME_RE.match(args.name):
        parser.error(
            f"invalid profile name {args.name!r}: use letters, digits, '.', '_' or '-'"
        )

    # A Slurm directive starts with `--`, which argparse reads as another option
    # unless it is attached with `=`. Leading whitespace is the other way past
    # that, so `--directive ' --qos=normal'` is accepted here rather than
    # reaching the job script with a space in it.
    if args.directives is not None:
        args.directives = [d.strip() for d in args.directives]

    if args.base:
        try:
            data = load_profile(args.base).model_dump()
        except (FileNotFoundError, ValueError) as e:
            print(f"ERROR: {e}", file=sys.stderr)
            return 1
    else:
        data = {}

    data["name"] = args.name
    for key, value in (
        ("scheduler", args.scheduler),
        ("account", args.account),
        ("partition", args.partition),
        ("nodes", args.nodes),
        ("cpus", args.cpus),
        ("mem", args.mem),
        ("time", args.time),
        ("select", args.select),
        ("extra_directives", args.directives),
        ("scratch_base", args.scratch_base),
    ):
        if value is not None:
            data[key] = value

    # Rebuild the shell block whenever any of its parts was given; otherwise keep
    # what --from supplied (so copying a profile to change only Slurm settings
    # does not discard its module loads).
    if args.modules or args.env_lines or args.venv or not args.base:
        data["env_setup"] = build_env_setup(
            args.modules, args.env_lines, args.venv, module_purge=not args.no_module_purge
        )

    try:
        profile = ClusterProfile(**data)  # validates types and rejects unknown keys
    except Exception as e:
        print(f"ERROR: invalid profile: {e}", file=sys.stderr)
        return 1

    text = render_profile(profile.model_dump())

    if args.dry_run:
        print(text, end="")
        return 0

    path = Path(args.output) if args.output else profiles_dir() / f"{args.name}.yaml"
    if path.exists() and not args.force:
        print(
            f"ERROR: {path} already exists — pass --force to overwrite.", file=sys.stderr
        )
        return 1
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    except OSError as e:
        print(
            f"ERROR: cannot write {path}: {e}\n"
            "Write it elsewhere with -o FILE and pass that path to `setup --profile`.",
            file=sys.stderr,
        )
        return 1

    # Round-trip the file we just wrote: a profile that setup cannot load is not
    # worth reporting as created.
    try:
        load_profile(str(path))
    except Exception as e:  # pragma: no cover — would mean a rendering bug
        print(f"ERROR: wrote {path} but it does not load back: {e}", file=sys.stderr)
        return 1

    print(f"Profile written: {path}")
    if args.output:
        print(f"Use it with    : naa-param setup ... --profile {path}")
    else:
        print(f"Use it with    : naa-param setup ... --profile {args.name}")
        print(f"Profiles now   : {', '.join(available_profiles())}")
    if not args.venv:
        print(
            "\nNote: env_setup has a placeholder activation line — edit it (or re-run "
            "with --venv PATH)\n      so the compute node can find `naa-param`."
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
